# Task7  Користувач вводить швидкість.
# Якщо швидкість більша за 90км\год – спитати де саме він  їде: місто чи траса.
# Якщо в місті то повідомити про штраф, якщо траса то попередження
# Якщо швидкість менша за 20км/год – спитати скільки років машині.
# Якщо їй більше 15 років – запропонувати купити нову, інакше запропонувати поїхати на СТО
# Інша швидкість – побажати гарної подорожі.

speed = float(input("Введіть швидкість: "))
if speed > 90:
    where = input("Місто чи траса?: ")
    if where == "місто":
        print("Вам виписано штраф!")
    else:
        print("Попередження! Знизьте швидкість!")
if speed < 20:
    car_age = float(input("Скільки років машині?: "))
    if car_age > 15:
        print("Поропоную купити нову")
    else:
        print("Вам треба на СТО")
else:
    print("Гарної дороги!")
